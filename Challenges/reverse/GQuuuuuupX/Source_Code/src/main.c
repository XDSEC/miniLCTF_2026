static uint64_t rotl64(uint64_t value, unsigned shift) {
    shift &= 63u;
    if (shift == 0u) {
        return value;
    }
    return (value << shift) | (value >> (64u - shift));
}

static uint8_t rotl8(uint8_t value, unsigned shift) {
    shift &= 7u;
    if (shift == 0u) {
        return value;
    }
    return (uint8_t)((value << shift) | (value >> (8u - shift)));
}

static uint64_t splitmix64_step(uint64_t *state) {
    uint64_t word;

    *state += UINT64_C(0x9E3779B97F4A7C15);
    word = *state;
    word = (word ^ (word >> 30u)) * UINT64_C(0xBF58476D1CE4E5B9);
    word = (word ^ (word >> 27u)) * UINT64_C(0x94D049BB133111EB);
    word ^= word >> 31u;
    return word;
}

static uint64_t seed_const(size_t index) {
    return g_seed_const_enc[index & 7u] ^
           (UINT64_C(0xC3A5C85C97CB3127) ^
            (UINT64_C(0x9E3779B97F4A7C15) * (uint64_t)((index & 7u) + 1u)));
}

static uint8_t material_byte(size_t index) {
    return g_material_blob[index] ^ (uint8_t)(0x5Du + 23u * index + (index >> 1u));
}

static uint64_t decode_material64(size_t word_index) {
    uint64_t word = 0;
    size_t base = word_index * 8u;
    size_t byte_index;

    for (byte_index = 0; byte_index < 8u; ++byte_index) {
        word |= (uint64_t)material_byte(base + byte_index) << (byte_index * 8u);
    }

    return word;
}

static uint64_t material_layout_seed(unsigned tag, unsigned key) {
    uint64_t span = tag < 2u ? BODY_LEN : 8u;
    uint64_t scale = tag == 0u ? DECOY_SCRATCH_WORDS :
                     tag == 1u ? REAL_SCRATCH_WORDS : MATERIAL_WORDS;
    unsigned rot = (unsigned)((key + 17u * (tag + 1u)) & 63u);

    if (rot == 0u) {
        rot = 11u + 7u * tag;
    }

    return seed_const((tag * 3u + 1u) & 7u) ^
           rotl64(seed_const((tag * 5u + 4u) & 7u), rot) ^
           (((uint64_t)key * UINT64_C(0x0101010101010101)) +
            ((uint64_t)(tag + 1u) * UINT64_C(0xA24BAED4963EE407))) ^
           ((span << 32u) | (scale & UINT64_C(0xFFFFFFFF)));
}

static void material_slot_sequence(unsigned tag, unsigned key, size_t count, size_t *out, uint8_t used[MATERIAL_WORDS]) {
    uint64_t state = material_layout_seed(tag, key);
    size_t logical_index;

    for (logical_index = 0; logical_index < count; ++logical_index) {
        size_t slot;
        size_t stride;
        uint64_t mix;
        state ^= ((uint64_t)(logical_index + 1u) * UINT64_C(0xD1342543DE82EF95));
        mix = splitmix64_step(&state);
        slot = (size_t)((mix ^ (mix >> 32u) ^
                        ((uint64_t)logical_index * UINT64_C(0x9E3779B1))) % MATERIAL_WORDS);
        stride = (size_t)(((mix >> 17u) & 0x1Fu) | 1u);
        while (used[slot] != 0u) {
            slot = (slot + stride) % MATERIAL_WORDS;
        }
        used[slot] = 1u;
        out[logical_index] = slot;
    }
}

static uint64_t material_word_mask(unsigned tag, unsigned key, size_t logical_index, size_t slot) {
    uint64_t seed = material_layout_seed(tag, key) ^
                    ((uint64_t)(slot + 1u) * UINT64_C(0x94D049BB133111EB)) ^
                    ((uint64_t)(logical_index + 1u) * UINT64_C(0xD6E8FEB86659FD93));
    uint64_t mix0;
    uint64_t mix1;
    unsigned rot = (unsigned)(((slot * 11u) + (logical_index * 7u) + key + (tag * 13u)) & 63u);

    mix0 = splitmix64_step(&seed);
    seed ^= seed_const((logical_index + tag) & 7u);
    mix1 = splitmix64_step(&seed);
    if (rot == 0u) {
        rot = 23u;
    }

    return mix0 ^ rotl64(mix1, rot) ^ seed_const((slot + tag) & 7u);
}

static void load_round_constants(uint64_t out[8]) {
    uint8_t used[MATERIAL_WORDS] = {0};
    size_t slots[8];
    size_t index;

    material_slot_sequence(ROUND_LAYOUT_TAG, ROUND_LAYOUT_KEY, 8u, slots, used);
    for (index = 0; index < 8u; ++index) {
        out[index] = decode_material64(slots[index]) ^
                     material_word_mask(ROUND_LAYOUT_TAG, ROUND_LAYOUT_KEY, index, slots[index]);
    }
}

static void load_masked_anchors(unsigned profile, uint64_t out[BODY_LEN]) {
    uint8_t used[MATERIAL_WORDS] = {0};
    size_t round_slots[8];
    size_t slots[BODY_LEN];
    size_t skip[BODY_LEN];
    size_t index;

    material_slot_sequence(ROUND_LAYOUT_TAG, ROUND_LAYOUT_KEY, 8u, round_slots, used);
    if (profile != 0u) {
        material_slot_sequence(0u, DECOY_KEY, BODY_LEN, skip, used);
    }
    material_slot_sequence(profile, (unsigned)g_stub_state.key, BODY_LEN, slots, used);

    for (index = 0; index < BODY_LEN; ++index) {
        out[index] = decode_material64(slots[index]) ^
                     material_word_mask(profile, (unsigned)g_stub_state.key, index, slots[index]);
    }
}

static void decode_round_program(unsigned profile, uint8_t out[ROUND_PROGRAM_LEN]) {
    size_t index;

    for (index = 0; index < ROUND_PROGRAM_LEN; ++index) {
        out[index] = g_round_program_enc[profile][index] ^
                     (uint8_t)(0xA7u + 13u * index + 37u * profile + 3u * g_stub_state.key) ^
                     rotl8((uint8_t)(g_stub_state.key + 0x11u * (index + 1u) + profile),
                           (unsigned)((index + profile) & 7u));
    }
}

static void decode_opcode_map(unsigned profile, uint8_t out[OPCODE_COUNT]) {
    size_t index;

    for (index = 0; index < OPCODE_COUNT; ++index) {
        out[index] = g_opcode_map_enc[profile][index] ^
                     (uint8_t)(0x33u + 19u * index + 41u * profile + 5u * g_stub_state.key) ^
                     rotl8((uint8_t)(g_stub_state.key ^ (0x29u * (index + 1u)) ^ profile),
                           (unsigned)((index + 3u * profile) & 7u));
    }
}

static uint8_t translate_opcode(uint8_t opcode, const uint8_t opcode_map[OPCODE_COUNT]) {
    size_t index;

    for (index = 0; index < OPCODE_COUNT; ++index) {
        if (opcode == opcode_map[index]) {
            return (uint8_t)index;
        }
    }

    return VM_INVALID;
}

static void arx_round_vm(uint64_t state[4], uint64_t msg, uint64_t tweak,
                         const uint8_t program[ROUND_PROGRAM_LEN],
                         const uint8_t opcode_map[OPCODE_COUNT]) {
    size_t pc = 0;

    for (;;) {
        uint8_t opcode = translate_opcode(program[pc++], opcode_map);

        switch (opcode) {
        case VM_ADD_XOR: {
            uint8_t dst = program[pc++];
            uint8_t src = program[pc++];
            state[dst] += state[src] + (msg ^ tweak);
            break;
        }
        case VM_ADD_ROLMSG: {
            uint8_t dst = program[pc++];
            uint8_t src = program[pc++];
            uint8_t rot = program[pc++];
            state[dst] += state[src] + rotl64(msg, rot);
            break;
        }
        case VM_ADD_ROLTWEAK: {
            uint8_t dst = program[pc++];
            uint8_t src = program[pc++];
            uint8_t rot = program[pc++];
            state[dst] += state[src] + rotl64(tweak, rot);
            break;
        }
        case VM_ADD_MSG_XOR_ROLTWEAK: {
            uint8_t dst = program[pc++];
            uint8_t src = program[pc++];
            uint8_t rot = program[pc++];
            state[dst] += state[src] + (msg ^ rotl64(tweak, rot));
            break;
        }
        case VM_ROLXOR: {
            uint8_t dst = program[pc++];
            uint8_t rot = program[pc++];
            uint8_t src = program[pc++];
            state[dst] = rotl64(state[dst], rot) ^ state[src];
            break;
        }
        case VM_ADDREG: {
            uint8_t dst = program[pc++];
            uint8_t src = program[pc++];
            state[dst] += state[src];
            break;
        }
        case VM_END:
            return;
        default:
            state[0] ^= UINT64_C(0xBAD0BAD0BAD0BAD0);
            return;
        }
    }
}

