static uint8_t transform_byte(uint8_t input, const uint64_t state[4], uint64_t step, size_t index) {
    uint8_t add0 = (uint8_t)(step >> 8u);
    uint8_t xor0 = (uint8_t)(step >> 16u);
    unsigned rot0 = ((unsigned)(step >> 24u) & 7u) + 1u;
    uint8_t add1 = (uint8_t)(step >> 32u);
    uint8_t xor1 = (uint8_t)(step >> 40u);
    unsigned rot1 = ((unsigned)(step >> 48u) & 7u) + 1u;
    uint8_t feed = (uint8_t)(step >> 56u);
    uint8_t s0 = state_byte(state[0], index);
    uint8_t s1 = state_byte(state[1], index + 3u);
    uint8_t s2 = state_byte(state[2], index + 5u);
    uint8_t s3 = state_byte(state[3], index + 1u);
    uint8_t lane = input ^ rotl8((uint8_t)(s0 + add0), rot0) ^ xor0;

    lane = rotl8((uint8_t)(lane + s1 + add1), rot1) ^ xor1;
    lane = (uint8_t)(lane + s2 + feed);
    return (uint8_t)(lane ^ s3);
}

static void compute_taps(unsigned profile, size_t index, const uint64_t state[4], const uint64_t *scratch,
                         uint64_t rolling, uint64_t taps[3]) {
    uint64_t mask = verifier_scratch_words(profile) - 1u;

    taps[0] = scratch[(rolling ^ state[0] ^
                      (UINT64_C(0x9E3779B97F4A7C15) * (uint64_t)index) ^ profile) & mask];
    taps[1] = scratch[(rotl64(rolling, 7u) + state[1] + taps[0] +
                      (uint64_t)g_stub_state.key + (uint64_t)index) & mask];
    taps[2] = scratch[(taps[0] ^ rotl64(taps[1], 13u) ^ state[3] ^
                      (UINT64_C(0xD1342543DE82EF95) * (uint64_t)index) ^
                      ((uint64_t)profile << 7u)) & mask];
}

static uint64_t derive_step(unsigned profile, size_t index, const uint64_t state[4],
                            const uint64_t *scratch, uint64_t rolling,
                            const uint64_t round_const[8], uint64_t raw) {
    uint64_t taps[3];
    uint64_t control;
    uint8_t add0;
    uint8_t xor0;
    unsigned rot0;
    uint8_t add1;
    uint8_t xor1;
    unsigned rot1;
    uint8_t feed;
    uint8_t target_mask;
    uint8_t target;

    compute_taps(profile, index, state, scratch, rolling, taps);
    control = (raw & ~UINT64_C(0xFF)) ^
              rotl64(taps[0], 7u) ^
              rotl64(taps[1], 19u) ^
              rotl64(taps[2], 31u) ^
              round_const[(index + profile) & 7u];

    add0 = (uint8_t)control;
    xor0 = (uint8_t)(control >> 8u);
    rot0 = (unsigned)(((control >> 16u) ^ (taps[0] >> 19u) ^ (taps[2] >> 24u) ^
                       (uint64_t)g_stub_state.key ^ (uint64_t)index) & 7u) + 1u;
    add1 = (uint8_t)(control >> 24u);
    xor1 = (uint8_t)(((control >> 32u) ^ (taps[1] >> 11u) ^
                      ((uint64_t)profile * 0x5Bu) ^ (uint64_t)index) & 0xFFu);
    rot1 = (unsigned)(((control >> 40u) ^ (taps[2] >> 29u) ^
                       (uint64_t)g_stub_state.key ^ (uint64_t)(index * 3u)) & 7u) + 1u;
    feed = (uint8_t)(((control >> 48u) + (control >> 56u) + (taps[0] >> 56u) +
                      (uint64_t)index + ((uint64_t)profile * 17u)) & 0xFFu);
    target_mask = (uint8_t)(((control >> 56u) ^
                             state_byte(taps[0], index) ^
                             state_byte(taps[2], index + 3u) ^
                             state_byte(state[3], index + 1u) ^
                             (uint64_t)g_stub_state.key ^
                             (uint64_t)(index * 7u)) & 0xFFu);
    target = (uint8_t)raw ^ target_mask;

    return pack_step(target, add0, xor0, rot0, add1, xor1, rot1, feed);
}

static void init_profile_state(unsigned profile, const uint64_t round_const[8],
                               const uint8_t round_program[ROUND_PROGRAM_LEN],
                               const uint8_t opcode_map[OPCODE_COUNT],
                               uint64_t state[4], uint64_t *scratch, uint64_t *rolling_out) {
    uint64_t key64 = state_mask_key();
    size_t scratch_words = verifier_scratch_words(profile);
    size_t index;

    state[0] = round_const[0] ^ key64 ^ rotl64(round_const[(profile + 4u) & 7u], 7u + profile);
    state[1] = round_const[1] ^ rotl64(key64, 9u) ^ round_const[(profile + 5u) & 7u] ^
               ((uint64_t)scratch_words << 1u);
    state[2] = round_const[2] ^ rotl64(key64, 17u) ^ round_const[(profile + 6u) & 7u] ^
               ((uint64_t)scratch_words << 7u);
    state[3] = round_const[3] ^ (((uint64_t)BODY_LEN << 32u) | (uint64_t)scratch_words) ^
               round_const[(profile + 7u) & 7u];

    for (index = 0; index < scratch_words; ++index) {
        uint64_t msg = round_const[(index + profile) & 7u] ^
                       (UINT64_C(0x9E3779B97F4A7C15) * (uint64_t)(index + 1u)) ^
                       rotl64(key64, (unsigned)(index & 31u) + 1u);
        uint64_t tweak = round_const[(index + profile + 3u) & 7u] ^
                         rotl64(msg, (unsigned)((index >> 3u) & 31u) + 1u) ^
                         (UINT64_C(0xD1342543DE82EF95) * (uint64_t)index);

        arx_round_vm(state, msg, tweak, round_program, opcode_map);
        scratch[index] = state[0] ^ rotl64(state[1], 11u) ^ state[2] ^
                         rotl64(state[3], 23u) ^ round_const[(index + profile + 5u) & 7u];
    }

    *rolling_out = round_const[(profile * 3u + 1u) & 7u] ^
                   state[profile & 3u] ^
                   scratch[(state[0] ^ state[2] ^ (uint64_t)g_stub_state.key) &
                           ((uint64_t)scratch_words - 1u)] ^
                   rotl64(key64, 13u + profile);
}

static void mix_body_byte(uint64_t state[4], uint64_t *scratch, unsigned profile, size_t index,
                          uint8_t body_byte, uint64_t step, const uint64_t round_const[8],
                          const uint8_t round_program[ROUND_PROGRAM_LEN],
                          const uint8_t opcode_map[OPCODE_COUNT]) {
    uint64_t mask = verifier_scratch_words(profile) - 1u;
    size_t rounds = verifier_step_rounds(profile);
    uint64_t lane = ((uint64_t)body_byte * UINT64_C(0x0101010101010101)) ^
                    rotl64(step, (unsigned)(((index * 5u) + profile) & 31u) + 1u);
    size_t round_index;

    for (round_index = 0; round_index < rounds; ++round_index) {
        uint64_t idx0 = (state[0] ^ state[2] ^ step ^
                         (UINT64_C(0x9E3779B97F4A7C15) * (uint64_t)(index + 1u)) ^
                         (uint64_t)round_index) & mask;
        uint64_t idx1 = (state[1] + scratch[idx0] +
                         rotl64(state[3], (unsigned)(((unsigned)body_byte + round_index) & 31u) + 1u)) &
                        mask;
        uint64_t idx2 = (idx0 ^ idx1 ^ (uint64_t)body_byte ^
                         (uint64_t)(round_index * 13u) ^ ((uint64_t)profile << 7u)) & mask;
        uint64_t mix = (scratch[idx0] +
                        rotl64(scratch[idx1] ^ lane ^ step,
                               (unsigned)(((index + round_index + body_byte) & 31u) + 1u)) +
                        scratch[idx2]);
        uint64_t msg = mix ^ lane ^ round_const[(index + round_index + profile) & 7u];
        uint64_t tweak = scratch[idx2] ^
                         round_const[(index + round_index + profile + 5u) & 7u] ^
                         rotl64(step, (unsigned)(((round_index + profile) & 31u) + 1u));

        arx_round_vm(state, msg, tweak, round_program, opcode_map);
        scratch[idx0] ^= state[3] + round_const[(round_index + profile) & 7u];
        scratch[idx1] += rotl64(state[1] ^ lane,
                                (unsigned)(((round_index ^ body_byte) & 31u) + 1u));
        scratch[idx2] ^= rotl64(state[2] + mix, 9u);
    }
}

static uint64_t update_rolling(unsigned profile, size_t index, const uint64_t state[4],
                               const uint64_t *scratch, uint64_t rolling,
                               const uint64_t round_const[8], uint64_t raw,
                               uint8_t body_byte, uint8_t target) {
    uint64_t mask = verifier_scratch_words(profile) - 1u;
    uint64_t mix0 = scratch[(rolling ^ raw ^ state[2] ^ (uint64_t)index) & mask];
    uint64_t mix1 = scratch[(rotl64(rolling, 9u) + mix0 + state[1] +
                             (uint64_t)target + (uint64_t)g_stub_state.key) & mask];

    return rotl64(rolling ^ raw ^ mix0 ^ state[0] ^
                  ((((uint64_t)body_byte) | ((uint64_t)target << 8u)) *
                   UINT64_C(0x9E3779B97F4A7C15)),
                  rolling_update_rotation(profile, index, target)) +
           mix1 +
           round_const[(index + profile + 6u) & 7u];
}

static int evaluate_profile(uint64_t *diff_out, const unsigned char *body, unsigned profile,
                            const uint64_t round_const[8],
                            const uint64_t masked_anchors[BODY_LEN]) {
    uint8_t round_program[ROUND_PROGRAM_LEN];
    uint8_t opcode_map[OPCODE_COUNT];
    uint64_t state[4];
    uint64_t *scratch;
    uint64_t diff = 0;
    uint64_t rolling = 0;
    size_t scratch_words = verifier_scratch_words(profile);
    size_t index;

    decode_round_program(profile, round_program);
    decode_opcode_map(profile, opcode_map);

    scratch = (uint64_t *)malloc(sizeof(*scratch) * scratch_words);
    if (scratch == NULL) {
        return 0;
    }

    init_profile_state(profile, round_const, round_program, opcode_map, state, scratch, &rolling);

    for (index = 0; index < BODY_LEN; ++index) {
        uint64_t raw = masked_anchors[index] ^ anchor_mask(profile, index, rolling, round_const);
        uint64_t step = derive_step(profile, index, state, scratch, rolling, round_const, raw);
        uint8_t target = (uint8_t)step;

        diff |= (uint64_t)(transform_byte(body[index], state, step, index) ^ target);
        rolling = update_rolling(profile, index, state, scratch, rolling, round_const,
                                 raw, body[index], target);
        mix_body_byte(state, scratch, profile, index, body[index], step, round_const,
                      round_program, opcode_map);
    }

    free(scratch);
    *diff_out = diff;
    return 1;
}

static int verify_body(const unsigned char *body) {
    uint64_t round_const[8];
    uint64_t masked_anchors[BODY_LEN];
    uint64_t diff = 0;
    unsigned profile = selected_profile();

    if (!legal_body(body)) {
        return 0;
    }

    load_round_constants(round_const);
    load_masked_anchors(profile, masked_anchors);

    if (!evaluate_profile(&diff, body, profile, round_const, masked_anchors)) {
        return 0;
    }

    return diff == 0;
}

static int verify_flag(const char *candidate) {
    size_t len = strlen(candidate);
    const unsigned char *body;

    if (len != (sizeof(PREFIX) - 1u) + BODY_LEN + 1u) {
        return 0;
    }

    if (strncmp(candidate, PREFIX, sizeof(PREFIX) - 1u) != 0) {
        return 0;
    }

    if (candidate[len - 1u] != '}') {
        return 0;
    }

    body = (const unsigned char *)candidate + (sizeof(PREFIX) - 1u);
    return verify_body(body);
}

static void trim_newline(char *buffer) {
    size_t len = strlen(buffer);

    if (len != 0u && buffer[len - 1u] == '\n') {
        buffer[len - 1u] = '\0';
    }
}

int main(int argc, char **argv) {
    char buffer[128];
    const char *candidate = buffer;

    if (argc > 1) {
        candidate = argv[1];
    } else {
        fputs("flag> ", stdout);
        fflush(stdout);

        if (fgets(buffer, sizeof(buffer), stdin) == NULL) {
            puts("input error");
            return 1;
        }

        trim_newline(buffer);
    }

    if (verify_flag(candidate)) {
        puts("correct!");
        return 0;
    }

    puts("try again~");
    return 1;
}
